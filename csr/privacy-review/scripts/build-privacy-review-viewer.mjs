#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
// Resolve through csr-recorder, which already declares rrweb as a dependency.
const require = createRequire(resolve(packageRoot, '..', 'csr-recorder', 'package.json'));
const rrwebDist = dirname(require.resolve('rrweb'));
const template = readFileSync(resolve(packageRoot, 'privacy-review-viewer.html'), 'utf8');
const css = readFileSync(resolve(rrwebDist, 'style.min.css'), 'utf8');
const javascript = readFileSync(resolve(rrwebDist, 'rrweb.umd.min.cjs'), 'utf8');

const html = template
  .replace('/* RRWEB_CSS */', () => css.replaceAll('</style', '<\\/style'))
  .replace('/* RRWEB_SCRIPT */', () => javascript.replaceAll('</script', '<\\/script'));

if (
  html.includes('/* RRWEB_CSS */') ||
  html.includes('/* RRWEB_SCRIPT */') ||
  !html.includes('<!-- EMBEDDED_RECORDING -->')
) {
  throw new Error('Privacy review viewer template was not filled');
}

const source = `// Generated by scripts/build-privacy-review-viewer.mjs. Do not edit.\nexport const viewerHtml: string = ${JSON.stringify(
  html,
)};\n`;
const sourcePath = resolve(packageRoot, 'src', 'privacy-review-viewer.generated.ts');
const formatOptions = prettier.resolveConfig.sync(sourcePath) ?? {};
writeFileSync(sourcePath, prettier.format(source, { ...formatOptions, parser: 'typescript' }));
